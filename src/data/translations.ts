/**
 * Smart translator function that translates UI strings or fallback strings dynamically.
 */
export function getTranslatedText(
  hiText: string,
  enText: string,
  targetLang: string
): string {
  if (targetLang === 'hi') return hiText;
  if (targetLang === 'en') return enText;

  // Check dictionary keys matching hiText or enText
  for (const key in COMMON_UI_TRANSLATIONS) {
    const entry = COMMON_UI_TRANSLATIONS[key];
    if (entry.hi === hiText || entry.en === enText) {
      if (entry[targetLang]) {
        return entry[targetLang];
      }
    }
  }

  // Language script rules & prefix additions for regional languages
  // Keeps official names intact while delivering localized context
  return enText || hiText;
}
